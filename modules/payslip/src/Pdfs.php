<?php

namespace Saan\Modules\Payslip;

use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\DB;

/**
 * Per-person PDF slips: content sniffing, size limit, name matching and the single way a stored PDF leaves the server.
 * - the type comes from the bytes (finfo and the %PDF- header), never from the client name or MIME; everything else is refused
 * - a plain scan refuses JavaScript, launch and embedded files (a courtesy: it cannot see inside compressed streams)
 * - the real protection is the delivery: attachment, nosniff and a sandboxing CSP, only through an authorised controller
 * - stored encrypted (Vault::putFile)
 */
final class Pdfs
{
    public static function maxBytes(): int
    {
        return min(Slips::MAX_PDF_MB, max(1, (int) config('saan.storage.max_upload_mb', 10))) * 1048576;
    }

    /** @return string the PDF bytes; aborts 422 with a Thai message otherwise */
    public static function inspect(UploadedFile $file): string
    {
        $err = self::problem($file);
        abort_if($err !== null, 422, $err);
        return (string) file_get_contents((string) $file->getRealPath());
    }

    /** null when acceptable, else a Thai reason. */
    public static function problem(UploadedFile $file): ?string
    {
        if (!$file->isValid()) return 'อัปโหลดไฟล์ไม่สำเร็จ';
        $path = (string) $file->getRealPath();
        $size = (int) $file->getSize();
        if ($size < 1) return 'ไฟล์ว่างเปล่า';
        if ($size > self::maxBytes()) return 'ไฟล์ใหญ่เกิน '.round(self::maxBytes() / 1048576).' MB';
        $mime = (string) (new \finfo(FILEINFO_MIME_TYPE))->file($path);
        $raw = (string) file_get_contents($path);
        if ($mime !== 'application/pdf' || !str_starts_with($raw, '%PDF-')) return 'รับเฉพาะไฟล์ PDF';
        $plain = preg_replace_callback('/#([0-9A-Fa-f]{2})/', fn ($m) => chr(hexdec($m[1])), $raw);
        if (preg_match('#/(JavaScript|JS|Launch|EmbeddedFile)(?![A-Za-z0-9])#', (string) $plain) === 1) return 'ไฟล์ PDF มีส่วนที่ระบบไม่รับ';
        return null;
    }

    /**
     * The payee whose code is the whole stem, else the LONGEST prefix of the stem that ends at a delimiter (_ - . or white space):
     * "T001.pdf", "T001_2569_01.pdf", "T001 สลิป.pdf" -> T001; with T1 and T1_2 both on file "T1_2_Jan.pdf" -> T1_2 (only T1 on file -> T1).
     * Never a partial token: "T10.pdf" is not T1.
     */
    public static function payeeFor(string $clientName): ?object
    {
        $stem = pathinfo(str_replace('\\', '/', basename(str_replace('\\', '/', $clientName))), PATHINFO_FILENAME);
        if ($stem === '') return null;
        $keys = [Payees::codeKey($stem)];
        if (preg_match_all('/[_\-.\s]/u', $stem, $m, PREG_OFFSET_CAPTURE)) foreach ($m[0] as [, $at]) $keys[] = Payees::codeKey(substr($stem, 0, $at));
        $keys = array_values(array_unique(array_filter($keys, fn ($k) => $k !== '')));
        if (!$keys) return null;
        // one query for every candidate; the longest matching code wins
        return DB::table('psl_payees')->where('school_id', Support::school())->whereIn('code_key', $keys)->get()
            ->sortByDesc(fn ($p) => mb_strlen((string) $p->code_key))->first();
    }

    /** Authorised download. $name is generated by the caller (never the client file name). */
    public static function respond(string $bytes, string $name)
    {
        return response($bytes, 200, [
            'Content-Type' => 'application/pdf', 'Content-Disposition' => 'attachment; filename="'.$name.'"', 'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'no-store, private', 'Content-Security-Policy' => "default-src 'none'; style-src 'unsafe-inline'; sandbox",
            'X-Robots-Tag' => 'noindex, nofollow, noarchive', 'Cross-Origin-Resource-Policy' => 'same-origin',
        ]);
    }
}
